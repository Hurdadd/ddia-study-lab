#!/usr/bin/env python3
"""Draw a snapshot of the repository's current stargazers as an SVG for the README.

GitHub's stargazer list carries a ``starred_at`` timestamp per account, so a
cumulative curve can be reconstructed from the current stargazers alone. That is
a snapshot, not an append-only history: an unstar removes its point, so the curve
cannot show drops. The SVG and the JSON beside it are regenerated by
``assets/build_stars.py`` and are served as repository files, so a README view
makes no third-party request.

The chart is a card: cream ground, gold step line, weekly ticks, a dotted month
boundary and a footer with the stars each month added. It stays legible on both
GitHub themes because it paints its own ground instead of relying on the page.
"""
from __future__ import annotations

import json
import subprocess
import urllib.request
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HISTORY = ROOT / 'assets' / 'star-history.json'
CHART = ROOT / 'assets' / 'star-history.svg'

WIDTH, HEIGHT = 880, 300
PAD_L, PAD_R, PAD_T, PAD_B = 52, 24, 68, 54
GROUND = '#f7f2e8'
GROUND_EDGE = '#e6dbc4'
INK = '#302828'
MUTED = '#6e665c'
FAINT = '#9b9184'
GOLD = '#b07d00'
GRID = '#ded2b8'
MONTHS = ('Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec')
FONT = "Verdana,Geneva,DejaVu Sans,sans-serif"


def fetch_stars(repo: str) -> list[str]:
    """Every current stargazer's timestamp, oldest first (paginated)."""
    stamps: list[str] = []
    page = 1
    while True:
        try:
            out = subprocess.run(
                ['gh', 'api', '-H', 'Accept: application/vnd.github.star+json',
                 f'repos/{repo}/stargazers?per_page=100&page={page}'],
                capture_output=True, text=True, check=True, timeout=60,
            ).stdout
            rows = json.loads(out)
        except (subprocess.SubprocessError, FileNotFoundError, json.JSONDecodeError):
            rows = _fetch_page_api(repo, page)
        for row in rows:
            stamp = row.get('starred_at')
            if stamp:
                stamps.append(stamp)
        if len(rows) < 100:
            break
        page += 1
    return sorted(stamps)


def _fetch_page_api(repo: str, page: int) -> list[dict]:
    request = urllib.request.Request(
        f'https://api.github.com/repos/{repo}/stargazers?per_page=100&page={page}',
        headers={'Accept': 'application/vnd.github.star+json',
                 'User-Agent': 'ddia-study-lab-build'},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read().decode('utf-8'))


def as_date(stamp: str) -> date:
    return datetime.fromisoformat(stamp.replace('Z', '+00:00')).date()


def nice_top(count: int) -> tuple[int, int]:
    """A round number above the count, and the tick step that reaches it."""
    for step in (1, 2, 5, 10, 20, 25, 50, 100, 200, 500, 1000, 2000, 5000):
        top = -(-count // step) * step
        if top // step <= 5:
            return max(top, step), step
    return count, max(1, count // 4)


def monthly_totals(stamps: list[str]) -> list[tuple[str, int]]:
    totals: dict[tuple[int, int], int] = {}
    for stamp in stamps:
        day = as_date(stamp)
        totals[(day.year, day.month)] = totals.get((day.year, day.month), 0) + 1
    return [(MONTHS[month - 1], count) for (_, month), count in sorted(totals.items())]


def render(stamps: list[str], repo: str, today: date | None = None) -> str:
    today = today or datetime.now(timezone.utc).date()
    days = [as_date(stamp) for stamp in stamps]
    count = len(days)
    first = days[0] if days else today
    plot_w = WIDTH - PAD_L - PAD_R
    plot_h = HEIGHT - PAD_T - PAD_B
    left, right = PAD_L, WIDTH - PAD_R
    top, bottom = PAD_T, HEIGHT - PAD_B

    # Open just before the first star: a long stretch of zero says little, and the
    # header already names the date the curve starts.
    start = first - timedelta(days=2)
    # End at the newest star, not at "now": a quiet week then produces no diff, and
    # the badge is the surface that carries the current number.
    end = max(days[-1] if days else first, first) + timedelta(days=1)
    span = max((end - start).days, 1)

    def x(day: date) -> float:
        return left + (day - start).days / span * plot_w

    top_value, step = nice_top(count)
    ticks = list(range(0, top_value + 1, step))

    def y(value: int) -> float:
        return bottom - (value / top_value) * plot_h

    # Step path: the count holds until the next star arrives.
    move = f'M {x(start):.1f} {y(0):.1f}'
    path = [move]
    for index, day in enumerate(days, start=1):
        path.append(f'H {x(day):.1f} V {y(index):.1f}')
    path.append(f'H {right:.1f}')
    line = ' '.join(path)
    area = f'{line} L {right:.1f} {y(0):.1f} L {left:.1f} {y(0):.1f} Z'

    if days:
        since = f'{first.day} {MONTHS[first.month - 1]} {first.year}'
        caption = f'Star count snapshot: {count} current stargazers since {since}'
        subtitle = f'current stargazers since {since}'
    else:
        caption = 'Star count snapshot: no current stargazers'
        subtitle = 'no current stargazers yet'
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" '
        f'viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-label="{caption}">',
        f'<title>{caption}</title>',
        f'<rect width="{WIDTH}" height="{HEIGHT}" rx="16" fill="{GROUND}" stroke="{GROUND_EDGE}"/>',
        '<defs>',
        '<linearGradient id="fill" x1="0" y1="0" x2="0" y2="1">',
        f'<stop offset="0" stop-color="{GOLD}" stop-opacity=".26"/>',
        f'<stop offset="1" stop-color="{GOLD}" stop-opacity=".02"/>',
        '</linearGradient>',
        '</defs>',
        f'<g font-family="{FONT}">',
    ]

    # Header: what this is, and the number it ends on.
    parts.append(
        f'<text x="{PAD_L}" y="28" font-size="10" letter-spacing="1.5" fill="{MUTED}">'
        f'STAR COUNT SNAPSHOT · {repo.upper()}</text>'
    )
    parts.append(f'<text x="{PAD_L}" y="47" font-size="12.5" fill="{FAINT}">{subtitle}</text>')
    parts.append(f'<text x="{right}" y="44" text-anchor="end" font-size="30" font-weight="bold" '
                 f'fill="{INK}">{count}</text>')
    number_width = 18.5 * len(str(count))
    parts.append(f'<text x="{right - number_width - 8:.1f}" y="44" text-anchor="end" font-size="11" '
                 f'fill="{FAINT}">stars</text>')

    # Grid and the value axis.
    for value in ticks:
        parts.append(f'<line x1="{left}" x2="{right}" y1="{y(value):.1f}" y2="{y(value):.1f}" '
                     f'stroke="{GRID}" stroke-width="1" stroke-dasharray="2 4"/>')
        parts.append(f'<text x="{left - 10}" y="{y(value) + 3.5:.1f}" text-anchor="end" '
                     f'font-size="10.5" fill="{FAINT}">{value}</text>')

    # Ticks: Mondays on a short history, month starts once the span needs it.
    monthly = span > 210
    cursor = start
    while cursor <= end:
        if cursor.day == 1 and x(cursor) > left + 24:
            parts.append(f'<line x1="{x(cursor):.1f}" x2="{x(cursor):.1f}" y1="{top}" y2="{bottom}" '
                         f'stroke="{GRID}" stroke-width="1" stroke-dasharray="1 5"/>')
        cursor += timedelta(days=1)

    if monthly:
        months_span = (end.year - start.year) * 12 + end.month - start.month + 1
        month_step = (1 if months_span <= 10 else 3 if months_span <= 20
                      else 6 if months_span <= 40 else 12)
        cursor = start
        while cursor <= end:
            index = (cursor.year - start.year) * 12 + cursor.month - start.month
            if cursor.day == 1 and index % month_step == 0:
                label = MONTHS[cursor.month - 1]
                if month_step >= 3:
                    label += f' {cursor.year % 100:02d}'
                parts.append(f'<text x="{x(cursor):.1f}" y="{bottom + 18}" text-anchor="middle" '
                             f'font-size="10.5" fill="{FAINT}">{label}</text>')
            cursor += timedelta(days=1)
    else:
        step_days = 7
        while span / step_days > 9:
            step_days += 7
        cursor = start + timedelta(days=(-start.weekday()) % 7)  # first Monday in view
        while cursor <= end:
            parts.append(f'<text x="{x(cursor):.1f}" y="{bottom + 18}" text-anchor="middle" '
                         f'font-size="10.5" fill="{FAINT}">{cursor.day} {MONTHS[cursor.month - 1]}</text>')
            cursor += timedelta(days=step_days)

    # The curve itself.
    parts.append(f'<path d="{area}" fill="url(#fill)"/>')
    parts.append(f'<path d="{line}" fill="none" stroke="{GOLD}" stroke-width="2.2" '
                 f'stroke-linejoin="round" stroke-linecap="round"/>')
    if count <= 120:
        for index, day in enumerate(days, start=1):
            parts.append(f'<circle cx="{x(day):.1f}" cy="{y(index):.1f}" r="3.1" fill="{GOLD}" '
                         f'stroke="{GROUND}" stroke-width="1.6"/>')

    # Footer: how many each month added.
    totals = monthly_totals(stamps)
    if len(totals) > 6:
        summary = '…   ·   ' + '   ·   '.join(f'{name} +{added}' for name, added in totals[-6:])
    else:
        summary = '   ·   '.join(f'{name} +{added}' for name, added in totals)
    parts.append(f'<text x="{left}" y="{HEIGHT - 16}" font-size="11" fill="{MUTED}">{summary}</text>')
    parts.append(f'<text x="{right}" y="{HEIGHT - 16}" text-anchor="end" font-size="10" '
                 f'fill="{FAINT}">current stargazers only · no unstar history</text>')

    parts.append('</g></svg>')
    return '\n'.join(parts) + '\n'


def write_history(stamps: list[str], repo: str) -> None:
    # Rewrite only when the list moved; a fresh `generated` stamp on every run would
    # make the scheduled job commit noise instead of a change.
    if HISTORY.exists():
        try:
            old = json.loads(HISTORY.read_text(encoding='utf-8'))
            if old.get('stars') == stamps and old.get('repo') == repo:
                return
        except json.JSONDecodeError:
            pass
    payload = {
        'repo': repo,
        'count': len(stamps),
        'generated': datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace('+00:00', 'Z'),
        'stars': stamps,
    }
    HISTORY.write_text(json.dumps(payload, indent=2) + '\n', encoding='utf-8')


def write_chart(stamps: list[str], repo: str, today: date | None = None) -> None:
    CHART.write_text(render(stamps, repo, today), encoding='utf-8')


def read_history() -> list[str]:
    if not HISTORY.exists():
        return []
    return json.loads(HISTORY.read_text(encoding='utf-8')).get('stars', [])


if __name__ == '__main__':
    stamps = fetch_stars('Hurdadd/ddia-study-lab')
    write_history(stamps, 'Hurdadd/ddia-study-lab')
    write_chart(stamps, 'Hurdadd/ddia-study-lab')
    print(f'{len(stamps)} stars, {stamps[0] if stamps else "none"} .. {stamps[-1] if stamps else ""}')
